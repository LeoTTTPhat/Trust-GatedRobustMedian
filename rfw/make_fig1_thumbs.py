"""Pixel data for the trigger examples drawn in Figure 1 (revision R2).

Takes one clean test image from each image dataset, applies the exact trigger
used in the experiments (data.py: digits 2x2 / Fashion-MNIST 3x3 bright patch in
the top-left corner), and writes TikZ macros that draw the clean and triggered
images pixel by pixel (black background, white ink, as the data are stored).
Output: ../results_r2/latex/fig1_thumbs.tex
"""
from __future__ import annotations

import os

import numpy as np
from sklearn.datasets import load_digits

from data import _fmnist

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'results_r2', 'latex', 'fig1_thumbs.tex')


def tikz_image(img, levels=None):
    """img: 2-D array in [0,1]. Returns TikZ fills (unit = one pixel, origin at the
    bottom-left of the image), skipping the black background, with horizontal runs
    of equal grey merged into one rectangle."""
    n_r, n_c = img.shape
    q = img if levels is None else np.round(img * (levels - 1)) / (levels - 1)
    cmds = [f'\\fill[black] (0,0) rectangle ({n_c},{n_r});']
    for r in range(n_r):
        y = n_r - 1 - r
        c = 0
        while c < n_c:
            v = q[r, c]
            e = c
            while e + 1 < n_c and q[r, e + 1] == v:
                e += 1
            if v > 0:
                pct = int(round(100 * v))
                cmds.append(f'\\fill[white!{pct}!black] ({c},{y}) rectangle ({e + 1},{y + 1});')
            c = e + 1
    return '%\n'.join(cmds)


def main():
    d = load_digits()
    X = d.data / 16.0
    sevens = np.where(d.target == 7)[0]
    # first '7' whose top-left 2x2 block is empty, so the trigger is visibly added
    idx = next(i for i in sevens if X[i].reshape(8, 8)[:2, :2].max() == 0)
    dig = X[idx].reshape(8, 8)
    dig_t = dig.copy()
    dig_t[:2, :2] = 1.0                       # data.py: trigger_idx [0,1,8,9], value 1.0

    fm = _fmnist(seed=0)
    j = 0                                      # first official test image
    assert fm['yte'][j] == 9                   # ankle boot
    img = fm['Xte'][j].reshape(28, 28)
    assert img[:3, :3].max() == 0
    img_t = img.copy()
    img_t[:3, :3] = 1.0                        # data.py: 3x3 patch, value 1.0

    with open(OUT, 'w') as f:
        f.write('% Generated by sourceCode/rfw/make_fig1_thumbs.py -- do not edit by hand.\n')
        f.write(f'% digits: load_digits() index {idx} (label 7); Fashion-MNIST: test image 0 (ankle boot).\n')
        f.write('\\newcommand{\\figDigitClean}{%\n' + tikz_image(dig) + '}\n')
        f.write('\\newcommand{\\figDigitTrig}{%\n' + tikz_image(dig_t) + '}\n')
        f.write('\\newcommand{\\figFmClean}{%\n' + tikz_image(img, levels=8) + '}\n')
        f.write('\\newcommand{\\figFmTrig}{%\n' + tikz_image(img_t, levels=8) + '}\n')
    print('wrote', OUT, '| digits index', idx)


if __name__ == '__main__':
    main()
